#!/usr/bin/env python3
"""Deterministic community index for a Graphify graph.json: no model call, ever.

`graphify cluster-only --no-label` leaves every community named "Community N", which tells a
reader nothing. Naming them needs an LLM backend that Graphify auto-picks from whichever API key
is set (docs/15). This names each community by the source files that dominate it and lists its
best-connected symbols instead, so the map stays offline and reproducible.

    python3 -I scripts/graphify-communities.py <map>/graphify-out/graph.json [--source <dir>] > <map>/COMMUNITIES.md

With --source, a "Map hygiene" section lists the files that dominate the map and the ones whose
header says they are generated (bindgen output, vendored amalgamations): they crowd the god nodes
and communities and belong in the source's .graphifyignore (docs/15 Layer 3). It reads only the
first lines of those files, as text.

Stdlib only. Run it with -I: graph.json is derived data, never code.
"""

import collections
import json
import os
import re
import sys

TOP_COMMUNITIES = 60
TOP_COUPLINGS = 50
TOP_FILES = 40
# A file holding this share of all nodes, and at least this many of them, is reported as
# dominating the map. The count keeps a small map quiet: in a 65-node crate every file with four
# symbols holds 5%, and a list naming every file says nothing.
DOMINANT_SHARE = 0.05
DOMINANT_MIN_NODES = 50
# Header lines read per file when looking for a generated-code marker.
HEADER_LINES = 12
GENERATED = re.compile(r"auto-?generated|@generated|generated by|bindgen|do not edit|code generated", re.I)


def generated_marker(source_dir: str, rel: str):
    """The first header line that marks `rel` as generated, or None. Never follows a path out
    of `source_dir` (graph.json is derived data and its paths are not trusted)."""
    root = os.path.realpath(source_dir)
    path = os.path.realpath(os.path.join(root, rel))
    if os.path.commonpath([root, path]) != root or not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8", errors="replace") as f:
        head = [line.strip() for _, line in zip(range(HEADER_LINES), f)]
    return next((line for line in head if GENERATED.search(line)), None)


def hygiene(per_file: collections.Counter, total: int, source_dir: str):
    """(file, node count, share, marker) for each file that dominates the map or is marked
    generated, largest first. Only files with symbols are checked: an unmapped file costs nothing."""
    rows = (
        (f, c, c / total, generated_marker(source_dir, f) if source_dir else None)
        for f, c in per_file.most_common()
    )
    return [r for r in rows if (r[2] >= DOMINANT_SHARE and r[1] >= DOMINANT_MIN_NODES) or r[3]]


def hygiene_lines(rows) -> list:
    if not rows:
        return [
            f"No file holds 5% of the nodes (and at least {DOMINANT_MIN_NODES} of them) or carries "
            "a generated-code marker."
        ]
    out = [
        "These files crowd the god nodes and communities. If one is generated, vendored or "
        "test code, add its line to the source's `.graphifyignore` and rebuild; a dominating "
        "file that is hand-written is the real core, so keep it.",
        "",
    ]
    for f, c, share, marker in rows:
        # "marker", not "generated": a header line can mention bindgen without being its output.
        why = f"marker: \"{marker[:80]}\"" if marker else "dominates"
        out.append(f"- `{f}`: {c} nodes ({share:.0%}), {why}")
    return out


def main(path: str, source_dir: str = "") -> str:
    with open(path, encoding="utf-8") as f:
        graph = json.load(f)
    nodes = {n["id"]: n for n in graph["nodes"]}
    edges = graph.get("links") or graph.get("edges") or []

    degree = collections.Counter()
    coupling = collections.Counter()
    for e in edges:
        degree[e["source"]] += 1
        degree[e["target"]] += 1
        a, b = nodes.get(e["source"]), nodes.get(e["target"])
        # EXTRACTED only: INFERRED edges are Graphify's guesses, even under --code-only.
        if a and b and e.get("confidence") == "EXTRACTED":
            fa, fb = a.get("source_file") or "", b.get("source_file") or ""
            if fa and fb and fa != fb:
                coupling[tuple(sorted((fa, fb)))] += 1

    communities = collections.defaultdict(list)
    for n in graph["nodes"]:
        communities[n.get("community")].append(n)

    def files_of(members):
        named = (n.get("source_file") for n in members)
        return collections.Counter(f for f in named if f).most_common(3)

    def hubs_of(members):
        return sorted(members, key=lambda n: (-degree[n["id"]], n["id"]))[:6]

    out = [
        "# Code map: deterministic community index",
        "",
        f"From `graph.json` built at commit `{graph.get('built_at_commit') or 'unknown'}`. "
        "Each community is named by its dominant source files, with no model call. "
        "Use it to find where to look, then read the files.",
        "",
        f"## Communities (largest {TOP_COMMUNITIES})",
        "",
    ]
    # Nodes Graphify left without a community (none on a clustered graph, but an unclustered
    # extract has them) are listed once, last, as "unassigned" rather than "CNone".
    ranked = sorted(communities.items(), key=lambda kv: (kv[0] is None, -len(kv[1]), str(kv[0])))
    for cid, members in ranked[:TOP_COMMUNITIES]:
        files = ", ".join(f"`{f}`×{c}" for f, c in files_of(members))
        hubs = ", ".join(f"`{n.get('label', n['id'])}`" for n in hubs_of(members))
        label = "unassigned" if cid is None else f"C{cid}"
        out.append(f"- **{label}** ({len(members)} nodes): {files} · hubs: {hubs}")

    out += ["", f"## Strongest cross-file coupling (EXTRACTED edges, top {TOP_COUPLINGS})", ""]
    out += [f"- `{a}` ↔ `{b}`: {c}" for (a, b), c in coupling.most_common(TOP_COUPLINGS)]

    per_file = collections.Counter(n.get("source_file") for n in graph["nodes"] if n.get("source_file"))
    out += ["", f"## Largest files by symbol count (top {TOP_FILES})", ""]
    out += [f"- `{f}`: {c}" for f, c in per_file.most_common(TOP_FILES)]

    if source_dir:
        out += ["", "## Map hygiene", ""]
        out += hygiene_lines(hygiene(per_file, max(len(graph["nodes"]), 1), source_dir))
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    args = sys.argv[1:]
    if len(args) == 3 and args[1] == "--source":
        sys.stdout.write(main(args[0], args[2]))
    elif len(args) == 1:
        sys.stdout.write(main(args[0]))
    else:
        sys.exit("usage: graphify-communities.py <graph.json> [--source <dir>]")
