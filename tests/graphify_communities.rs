//! scripts/graphify-communities.py's Map hygiene list under test (docs/15 Layer 3): which files it
//! reports, and that it never reads a file outside `--source`, whether `graph.json` names it with
//! `..` or through a symlink. Runs the real script on a scratch tree; `graph.json` is hand-built.
#![allow(
    clippy::unwrap_used,
    reason = "test helpers outside #[test] fns; HTC-6 binds shipping code"
)]

use std::fs;
use std::path::Path;
use std::process::Command;

use serde_json::json;
use tempfile::TempDir;

const SCRIPT: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/scripts/graphify-communities.py"
);

/// `count` nodes in `file`, all in community 0.
fn nodes(file: &str, count: usize) -> Vec<serde_json::Value> {
    (0..count)
        .map(|i| json!({ "id": format!("{file}#{i}"), "source_file": file, "community": 0 }))
        .collect()
}

fn run(graph: &Path, source: Option<&Path>) -> String {
    let mut cmd = Command::new("python3");
    cmd.arg("-I").arg(SCRIPT).arg(graph);
    if let Some(dir) = source {
        cmd.arg("--source").arg(dir);
    }
    let out = cmd.output().unwrap();
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    String::from_utf8(out.stdout).unwrap()
}

fn hygiene(md: &str) -> Vec<&str> {
    md.split("## Map hygiene")
        .nth(1)
        .unwrap_or_default()
        .lines()
        .filter(|l| l.starts_with("- "))
        .collect()
}

#[test]
fn hygiene_lists_marked_and_dominating_files_and_never_reads_outside_the_source() {
    let tmp = TempDir::new().unwrap();
    let src = tmp.path().join("src");
    fs::create_dir_all(&src).unwrap();
    // Outside the source, and marked: a row quoting this marker would prove it was read.
    fs::write(
        tmp.path().join("outside.rs"),
        "// @generated OUTSIDE do not edit\n",
    )
    .unwrap();
    std::os::unix::fs::symlink(tmp.path().join("outside.rs"), src.join("link.rs")).unwrap();
    fs::write(src.join("core.rs"), "pub fn core() {}\n").unwrap();
    fs::write(src.join("small.rs"), "pub fn small() {}\n").unwrap();
    fs::write(
        src.join("gen.rs"),
        "//! FFI\n/* automatically generated by rust-bindgen 0.72.0 */\n",
    )
    .unwrap();

    // 44 nodes: core.rs dominates (91%); every other file is under 5%.
    let all: Vec<_> = [
        nodes("core.rs", 40),
        nodes("gen.rs", 1),
        nodes("small.rs", 1),
        nodes("../outside.rs", 1),
        nodes("link.rs", 1),
    ]
    .concat();
    let graph = tmp.path().join("graph.json");
    fs::write(&graph, json!({ "nodes": all, "links": [] }).to_string()).unwrap();

    let md = run(&graph, Some(&src));
    let rows = hygiene(&md);
    assert_eq!(rows.len(), 2, "{rows:#?}");
    assert_eq!(rows[0], "- `core.rs`: 40 nodes (91%), dominates");
    assert_eq!(
        rows[1],
        "- `gen.rs`: 1 nodes (2%), marker: \"/* automatically generated by rust-bindgen 0.72.0 */\""
    );
    assert!(
        !md.contains("OUTSIDE"),
        "a file outside --source was read:\n{md}"
    );

    // Without --source the section is absent: the output is what it was before the list existed.
    assert!(!run(&graph, None).contains("Map hygiene"));
}

#[test]
fn hygiene_says_so_when_nothing_crowds_the_map() {
    let tmp = TempDir::new().unwrap();
    let src = tmp.path().join("src");
    fs::create_dir_all(&src).unwrap();
    let all: Vec<_> = (0..25)
        .flat_map(|i| {
            let f = format!("f{i}.rs");
            fs::write(src.join(&f), "pub fn f() {}\n").unwrap();
            nodes(&f, 1)
        })
        .collect();
    let graph = tmp.path().join("graph.json");
    fs::write(&graph, json!({ "nodes": all, "links": [] }).to_string()).unwrap();
    let md = run(&graph, Some(&src));
    assert!(hygiene(&md).is_empty(), "{md}");
    assert!(md.contains("No file holds 5% of the nodes or carries a generated-code marker."));
}
